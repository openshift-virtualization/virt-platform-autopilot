#!/usr/bin/env python3
"""
Decide whether a PR changes, introduces, or promotes GA assets.

Feature semantics (maturity, membership, opt-in gates, supporting-file
references) are read from docs/generated/feature-status.json — generated by
cmd/feature-status-gen with the production derivation in pkg/assets — for
the PR head (the caller regenerates it first) and for the base revision
(via git show). The metadata catalog is parsed only for what the JSON does
not carry: asset paths (to map changed files to assets) and
excluded_assets.

The verdict (ga_assets_changed) is true when the PR changes:
  - framework or feature maturity (graduations, including changes expressed
    through asset install modes rather than `maturity:` lines)
  - new GA feature declarations, or removed GA features
  - the asset set of a feature that is (or becomes) GA
  - any catalog field of a GA asset (path, install, conditions, params, ...)
  - templates of GA assets, or of assets excluded from feature tracking
    (framework-level, e.g. hco-golden-config), or files those templates
    reference via readAsset (the supporting_files entries of the generated
    JSON)

Changed files under assets/active/ that no asset owns — neither cataloged
nor referenced — are not part of rendered output and do not flag the PR.

The ga-assets-detection workflow computes this verdict for every push and
the ga-assets-labeler workflow mirrors it into the ga-assets-changed
label. The QE approval policy on top of that fact (gate on the
iuo-qe-approved label, restricted to QE approvers) lands separately.

The verdict is data, not a failure: the script always exits 0 and reports
`ga_assets_changed=true|false` (written to $GITHUB_OUTPUT when set) plus the
list of reasons. Any input problem (missing or unparsable artifacts,
unexpected error) yields a true verdict, so a broken run cannot leave a
GA-affecting change unrecorded.

Usage: check-ga-assets-changed.py [--base-rev REV]
"""

import argparse
import json
import os
import posixpath
import subprocess
import sys

import yaml

METADATA = "assets/active/metadata.yaml"
STATUS_JSON = "docs/generated/feature-status.json"
ASSETS_PREFIX = "assets/active/"
# Admin files that live under assets/ but never affect rendered output.
NON_ASSET_BASENAMES = {"OWNERS"}


def git_changed_files(base_rev):
    out = subprocess.run(
        ["git", "diff", "--name-only", "--no-renames", f"{base_rev}...HEAD"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return [line for line in out.splitlines() if line]


def git_show(base_rev, path):
    result = subprocess.run(
        ["git", "show", f"{base_rev}:{path}"], capture_output=True, text=True
    )
    # A non-zero exit means the file does not exist on the base (new file).
    return result.stdout if result.returncode == 0 else None


def read_text(path):
    try:
        with open(path) as fh:
            return fh.read()
    except FileNotFoundError:
        return None


def parse_catalog(text, source):
    """Return (catalog, error). An empty text is an empty catalog."""
    if text is None:
        return None, f"{source} is missing"
    if not text.strip():
        return {}, None
    try:
        return yaml.safe_load(text) or {}, None
    except yaml.YAMLError as exc:
        return None, f"{source} could not be parsed: {exc}"


def parse_status(text, source):
    """Return (feature-status doc, error)."""
    if text is None:
        return None, f"{source} is missing"
    try:
        return json.loads(text), None
    except ValueError as exc:
        return None, f"{source} could not be parsed: {exc}"


def asset_list(catalog):
    return catalog.get("assets") or []


def excluded_assets(catalog):
    return set(catalog.get("excluded_assets") or [])


# --- File-to-asset mapping, consumed by phase 3 -----------------------------
def cataloged_assets(rel_path, catalog):
    """Assets whose cataloged path is exactly the file."""
    return {a["name"] for a in asset_list(catalog) if a.get("path") == rel_path}


def reference_map(status):
    """
    Reverse of the generated JSON's assets section: supporting file path ->
    asset names whose template references it via readAsset. Revisions of
    the JSON predating the assets section yield an empty map.
    """
    mapping = {}
    for asset in status.get("assets") or []:
        for path in asset.get("supporting_files") or []:
            mapping.setdefault(path, set()).add(asset["name"])
    return mapping


def file_assets(rel_path, base, head, base_refs, head_refs):
    """Assets owning the file: exact catalog match or readAsset reference."""
    names = cataloged_assets(rel_path, base) | cataloged_assets(rel_path, head)
    return names | base_refs.get(rel_path, set()) | head_refs.get(rel_path, set())


# ---------------------------------------------------------------------------
# Detection phases
#
# analyze() unions three independent reason sets, each answering a different
# question about the same base...head diff:
#
#   Phase 1 - status_reasons:   what changed in feature semantics?
#                               (diff of the two generated feature-status
#                               JSONs: maturity, GA membership, add/remove)
#   Phase 2 - metadata_reasons: what changed in catalog fields the JSON does
#                               not carry? (excluded_assets, any field of a
#                               GA asset in metadata.yaml)
#   Phase 3 - file_reasons:     which changed files under assets/active/
#                               belong to GA assets? (by cataloged path or
#                               by readAsset reference)
#
# Any reason from any phase sets ga_assets_changed=true.
# ---------------------------------------------------------------------------


# --- Phase 1: feature semantics from the generated feature-status JSONs ----
def status_reasons(base_status, head_status):
    """Reasons derived from the generated feature-status JSONs."""
    reasons = []

    base_framework = base_status.get("framework") or {}
    head_framework = head_status.get("framework") or {}
    base_key = (base_framework.get("maturity"), base_framework.get("opt_in"))
    head_key = (head_framework.get("maturity"), head_framework.get("opt_in"))
    if base_key != head_key:
        reasons.append(f"framework maturity/opt-in changed: {base_key} -> {head_key}")

    base_features = {f["name"]: f for f in base_status.get("features") or []}
    head_features = {f["name"]: f for f in head_status.get("features") or []}
    for name in sorted(set(base_features) | set(head_features)):
        base_feature = base_features.get(name)
        head_feature = head_features.get(name)
        if head_feature and not base_feature:
            if head_feature.get("maturity") == "GA":
                reasons.append(f"new GA feature declared: {name}")
            continue
        if base_feature and not head_feature:
            # The generated JSON carries only effective maturity, so explicit
            # and derived previews cannot be told apart; removals of GA
            # features always flag.
            if base_feature.get("maturity") == "GA":
                reasons.append(f"GA feature removed: {name}")
            continue
        base_maturity = base_feature.get("maturity")
        head_maturity = head_feature.get("maturity")
        if base_maturity != head_maturity:
            reasons.append(
                f"maturity of feature '{name}' changed: "
                f"{base_maturity} -> {head_maturity}"
            )
        # Membership comparison requires the assets field on both sides; the
        # guard keeps pre-assets revisions of the JSON from producing false
        # positives until every open PR has rebased onto the new format.
        if "assets" not in base_feature or "assets" not in head_feature:
            continue
        base_members = base_feature.get("assets") or []
        head_members = head_feature.get("assets") or []
        if base_members != head_members and "GA" in (base_maturity, head_maturity):
            reasons.append(
                f"asset set of GA feature '{name}' changed: "
                f"+{sorted(set(head_members) - set(base_members))} "
                f"-{sorted(set(base_members) - set(head_members))}"
            )
    return reasons


# --- GA surface shared by phases 2 and 3 ------------------------------------
def ga_related_assets(base_status, head_status, base_catalog, head_catalog):
    """
    Assets belonging to a GA feature (per the generated status JSONs), or
    excluded from feature tracking (framework-level assets).
    """
    related = excluded_assets(base_catalog) | excluded_assets(head_catalog)
    for status in (base_status, head_status):
        for feature in status.get("features") or []:
            if feature.get("maturity") == "GA":
                related.update(feature.get("assets") or [])
    return related


# --- Phase 2: catalog fields the status JSON does not carry -----------------
def metadata_reasons(base, head, ga_related):
    """Reasons derived from catalog fields the status JSON does not carry."""
    reasons = []

    base_excluded = excluded_assets(base)
    head_excluded = excluded_assets(head)
    if base_excluded != head_excluded:
        reasons.append(
            "excluded_assets changed: "
            f"+{sorted(head_excluded - base_excluded)} "
            f"-{sorted(base_excluded - head_excluded)}"
        )

    base_assets = {a["name"]: a for a in asset_list(base)}
    head_assets = {a["name"]: a for a in asset_list(head)}
    for name in sorted(set(base_assets) | set(head_assets)):
        base_asset = base_assets.get(name)
        head_asset = head_assets.get(name)
        if not base_asset or not head_asset or name not in ga_related:
            continue
        changed = sorted(
            field
            for field in set(base_asset) | set(head_asset)
            if base_asset.get(field) != head_asset.get(field)
        )
        if changed:
            reasons.append(
                f"metadata of GA asset '{name}' changed fields: {', '.join(changed)}"
            )
    return reasons


# --- Phase 3: changed files under assets/active/ ----------------------------
def file_reasons(base, head, files, ga_related, base_refs, head_refs):
    """Reasons derived from changed files under assets/active/."""
    reasons = []
    for path in sorted(files):
        if not path.startswith(ASSETS_PREFIX) or path == METADATA:
            continue
        if posixpath.basename(path) in NON_ASSET_BASENAMES:
            continue
        rel_path = path[len("assets/"):]
        names = file_assets(rel_path, base, head, base_refs, head_refs)
        if names & ga_related:
            reasons.append(
                f"'{path}' affects GA assets: {', '.join(sorted(names & ga_related))}"
            )
    return reasons


def analyze(base, head, base_status, head_status, files):
    """Union of the three detection phases: semantics, catalog, files."""
    ga_related = ga_related_assets(base_status, head_status, base, head)
    base_refs = reference_map(base_status)
    head_refs = reference_map(head_status)
    return (
        status_reasons(base_status, head_status)
        + metadata_reasons(base, head, ga_related)
        + file_reasons(base, head, files, ga_related, base_refs, head_refs)
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--base-rev",
        default="origin/main",
        help="git revision the PR is compared against (default: %(default)s)",
    )
    args = parser.parse_args()

    try:
        files = git_changed_files(args.base_rev)
        base, base_meta_error = parse_catalog(
            git_show(args.base_rev, METADATA), f"base {METADATA}"
        )
        head, head_meta_error = parse_catalog(read_text(METADATA), METADATA)
        base_status, base_status_error = parse_status(
            git_show(args.base_rev, STATUS_JSON), f"base {STATUS_JSON}"
        )
        head_status, head_status_error = parse_status(
            read_text(STATUS_JSON), STATUS_JSON
        )

        reasons = [
            error
            for error in (
                base_meta_error,
                head_meta_error,
                base_status_error,
                head_status_error,
            )
            if error
        ]
        if not reasons:
            reasons = analyze(base, head, base_status, head_status, files)
    except Exception as exc:  # noqa: BLE001 - a broken run must not bypass the gate
        reasons = [f"internal error while computing the verdict: {exc}"]

    verdict = "true" if reasons else "false"
    github_output = os.environ.get("GITHUB_OUTPUT")
    if github_output:
        with open(github_output, "a") as fh:
            fh.write(f"ga_assets_changed={verdict}\n")
    print(f"ga-assets-changed: {verdict}")
    for reason in reasons:
        print(f"  - {reason}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
